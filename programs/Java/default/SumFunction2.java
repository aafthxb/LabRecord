//Sum using function
//Function with no arguments and no return value

class SumFunction2 {
    void sum() {
        int a = 5;
        int b = 6;
        int c = a + b;
        System.out.println("Sum = " + c);
    }

    public static void main(String[] args) {
        SumFunction2 obj = new SumFunction2();
        obj.sum();
    }
}
